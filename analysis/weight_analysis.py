def track_weight_norms(results_json_path: str) -> Tuple[List[int], List[float]]:
    """
    Extract weight norm evolution from a results.json file.

    Args:
        results_json_path: Path to the results.json file generated by the training loop.

    Returns:
        Tuple of (steps, weight_norms).
    """
    with open(results_json_path, 'r') as f:
        data = json.load(f)

    steps = []
    norms = []

    if "history" in data:
        for entry in data["history"]:
            steps.append(entry["step"])
            norms.append(entry["weight_norm"])

    return steps, norms

def plot_weight_norm_evolution(condition_paths: Dict[str, str], save_path: str = "results/figures/weight_norms.png"):
    """
    Plot the evolution of weight norms for multiple conditions.

    Args:
        condition_paths: Dictionary mapping condition names to their results.json paths.
        save_path: Path to save the plot.
    """
    os.makedirs(os.path.dirname(save_path), exist_ok=True)
    plt.figure(figsize=(10, 6))

    for condition, path in condition_paths.items():
        if os.path.exists(path):
            steps, norms = track_weight_norms(path)
            plt.plot(steps, norms, label=condition)

    plt.xlabel("Training Steps")
    plt.ylabel("L2 Weight Norm")
    plt.title("Weight Norm Evolution During Training")
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(save_path, dpi=300)
    plt.close()

