import json
from pathlib import Path
from typing import Dict, Any, List
import numpy as np

try:
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    HAS_MATPLOTLIB = True
except ImportError:
    HAS_MATPLOTLIB = False

def plot_kaplan_meier_survival(stats_data: Dict[str, Any], output_path: str) -> None:
    """
    Render Kaplan-Meier style survival curves for grokking.

    Args:
        stats_data: Dictionary of statistics generated by the analyzer.
        output_path: Path to save the generated plot.
    """
    if not HAS_MATPLOTLIB:
        print("matplotlib not available, skipping plot")
        return

    plt.figure(figsize=(10, 6))

    for cond_name, stats in stats_data.items():
        times = np.array(stats['times'])
        events = np.array(stats['events'])

        # Sort times for KM curve
        sort_idx = np.argsort(times)
        t_sorted = times[sort_idx]
        e_sorted = events[sort_idx]

        unique_times = np.unique(t_sorted)
        survival = []
        n_at_risk = len(times)

        current_surv = 1.0

        for t in unique_times:
            # count events at this time
            d = np.sum((t_sorted == t) & (e_sorted == 1))
            # count censored at this time
            c = np.sum((t_sorted == t) & (e_sorted == 0))

            if n_at_risk > 0:
                current_surv = current_surv * (1 - d / n_at_risk)
            survival.append(current_surv)

            n_at_risk -= (d + c)

        plt.step(unique_times, survival, where='post', label=f"{cond_name} (frac={stats['grok_fraction']:.2f})")

    plt.xlabel('Training Steps')
    plt.ylabel('Proportion Not Grokked (Survival)')
    plt.title('Kaplan-Meier Survival Curves for Grokking')
    plt.ylim(0, 1.05)
    plt.legend()
    plt.grid(True, alpha=0.3)

    plt.savefig(output_path, dpi=150, bbox_inches='tight')
    plt.close()

def plot_grokking_vs_severity_with_cis(stats_data: Dict[str, Any], output_path: str) -> None:
    """
    Visualize median grokking steps with confidence intervals.

    Args:
        stats_data: Dictionary of statistics generated by the analyzer.
        output_path: Path to save the generated plot.
    """
    if not HAS_MATPLOTLIB:
        return

    conditions = []
    medians = []
    errors = []

    # Sort conditions based on severity if possible, or alphabetically
    order = ["pure", "low_collapse", "medium_collapse", "high_collapse", "severe_collapse"]
    sorted_conds = sorted(list(stats_data.keys()), key=lambda x: order.index(x) if x in order else len(order))

    for cond in sorted_conds:
        stats = stats_data[cond]
        if not np.isnan(stats['median']):
            conditions.append(cond)
            medians.append(stats['median'])
            # Error bars need to be relative to median for matplotlib
            lower_err = stats['median'] - stats['lower_ci']
            upper_err = stats['upper_ci'] - stats['median']
            errors.append([max(0, lower_err), max(0, upper_err)])

    if not conditions:
        return

    errors = np.array(errors).T # shape (2, N) for matplotlib

    plt.figure(figsize=(10, 6))
    plt.errorbar(conditions, medians, yerr=errors, fmt='o-', capsize=5, markersize=8)
    plt.xlabel('Condition')
    plt.ylabel('Median Grokking Step')
    plt.title('Grokking Timing vs Collapse Severity (with 95% CI)')
    plt.grid(True, alpha=0.3)
    plt.xticks(rotation=45)

    plt.savefig(output_path, dpi=150, bbox_inches='tight')
    plt.close()

def plot_weight_norm_trajectories(results_dir: str, output_path: str) -> None:
    """
    Show the average weight norm decay over time across conditions.

    Args:
        results_dir: Path to multi-seed results directory.
        output_path: Path to save the generated plot.
    """
    if not HAS_MATPLOTLIB:
        return

    results_path = Path(results_dir)
    conditions = {}

    # Structure is results/multi_seed/<seed>/<condition>/results.json
    if results_path.exists():
        for seed_dir in results_path.iterdir():
            if not seed_dir.is_dir():
                continue
            for cond_dir in seed_dir.iterdir():
                if not cond_dir.is_dir():
                    continue
                cond_name = cond_dir.name
                res_file = cond_dir / "results.json"
                if res_file.exists():
                    with open(res_file, "r") as f:
                        data = json.load(f)
                    if cond_name not in conditions:
                        conditions[cond_name] = []

                    history = data.get("history", [])
                    steps = [e["step"] for e in history]
                    norms = [e.get("weight_norm", 0) for e in history]

                    if steps and norms:
                        conditions[cond_name].append((steps, norms))

    plt.figure(figsize=(12, 7))

    colors = {
        "pure": "#2ecc71",
        "low_collapse": "#3498db",
        "medium_collapse": "#f39c12",
        "high_collapse": "#e74c3c",
        "severe_collapse": "#8e44ad",
    }

    for cond_name, runs_data in conditions.items():
        if not runs_data:
            continue

        color = colors.get(cond_name, "gray")

        # Plot individual runs semi-transparent
        for steps, norms in runs_data:
            plt.plot(steps, norms, color=color, alpha=0.2)

        # Calculate and plot average
        # Assumes steps are identical across runs
        try:
            avg_norms = np.mean([norms for _, norms in runs_data], axis=0)
            plt.plot(runs_data[0][0], avg_norms, color=color, linewidth=2, label=cond_name)
        except ValueError:
            # Different length trajectories, skip average
            plt.plot([], [], color=color, linewidth=2, label=f"{cond_name} (runs)")

    plt.xlabel('Step')
    plt.ylabel('Weight Norm')
    plt.title('Weight Norm Trajectories across Conditions')
    plt.legend()
    plt.grid(True, alpha=0.3)

    plt.savefig(output_path, dpi=150, bbox_inches='tight')
    plt.close()
